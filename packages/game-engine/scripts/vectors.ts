// Generates test-vectors/*.json from the TypeScript engine (the reference implementation).
// The Dart engine's tests replay the same inputs and must produce identical outputs.
//   --check  fail if the committed vectors differ from what the engine produces now
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { WyrItem } from '@mirthmix/content';
import { createRng, seededShuffle } from '../src/random.ts';
import {
  buildPool,
  createWyrSession,
  reduceWyr,
  wyrResults,
  type WyrAction,
  type WyrConfig,
} from '../src/would-you-rather.ts';

const outPath = join(dirname(fileURLToPath(import.meta.url)), '../test-vectors/would-you-rather.json');

const items: WyrItem[] = [
  ...['01', '02', '03', '04', '05'].map((n) => ({
    id: `wyr-casual-0${n}`,
    category: 'casual',
    a: `Casual A${n}`,
    b: `Casual B${n}`,
  })),
  ...['01', '02', '03'].map((n) => ({
    id: `wyr-funny-0${n}`,
    category: 'funny',
    a: `Funny A${n}`,
    b: `Funny B${n}`,
  })),
];

const V = (side: 'a' | 'b'): WyrAction => ({ type: 'vote', side });
const NEXT: WyrAction = { type: 'next' };
const SKIP: WyrAction = { type: 'skip' };
const REVEAL: WyrAction = { type: 'reveal' };
const UNDO: WyrAction = { type: 'undo' };

const scenarios: { name: string; config: WyrConfig; actions: WyrAction[] }[] = [
  {
    name: 'three rounds with votes, reveal and undo',
    config: { categoryIds: ['casual', 'funny'], rounds: 3, seed: 42 },
    actions: [V('a'), V('a'), V('b'), REVEAL, NEXT, V('b'), V('b'), V('a'), UNDO, NEXT, V('a'), V('b'), NEXT],
  },
  {
    name: 'votes after reveal are ignored',
    config: { categoryIds: ['casual'], rounds: 2, seed: 7 },
    actions: [V('a'), REVEAL, V('b'), UNDO, NEXT, V('b'), NEXT],
  },
  {
    name: 'player cap limits votes per round',
    config: { categoryIds: ['casual'], rounds: 1, seed: 99, playerCount: 3 },
    actions: [V('a'), V('a'), V('b'), V('b'), V('a'), NEXT],
  },
  {
    name: 'skip swaps in spare questions, then spends rounds when none are left',
    config: { categoryIds: ['funny'], rounds: 2, seed: 2024 },
    actions: [SKIP, V('a'), V('a'), NEXT, SKIP],
  },
  {
    name: 'rounds capped by pool size; actions after finish are ignored',
    config: { categoryIds: ['funny'], rounds: 10, seed: 1 },
    actions: [V('a'), V('b'), NEXT, V('a'), V('a'), V('a'), NEXT, NEXT, V('a'), NEXT, SKIP],
  },
  {
    name: 'unfinished session',
    config: { categoryIds: ['casual', 'funny'], rounds: 5, seed: 4294967295 },
    actions: [V('b'), NEXT, SKIP, V('a'), V('a')],
  },
];

const vectors = {
  $comment:
    'GENERATED by packages/game-engine/scripts/vectors.ts from the TypeScript engine. Do not edit.',
  rng: [0, 1, 42, 2024, 4294967295].map((seed) => {
    const next = createRng(seed);
    return { seed, values: Array.from({ length: 6 }, () => next()) };
  }),
  shuffle: [0, 42, 123456].map((seed) => ({
    seed,
    input: items.map((i) => i.id),
    output: seededShuffle(
      items.map((i) => i.id),
      seed,
    ),
  })),
  items,
  wyr: scenarios.map(({ name, config, actions }) => {
    let state = createWyrSession(buildPool(items, config.categoryIds), config);
    for (const a of actions) state = reduceWyr(state, a);
    return {
      name,
      config,
      actions,
      expected: {
        order: state.order,
        totalRounds: state.totalRounds,
        status: state.status,
        skips: state.skips,
        rounds: state.rounds,
        current: state.current,
        results: wyrResults(state),
      },
    };
  }),
};

const json = JSON.stringify(vectors, null, 2) + '\n';
if (process.argv.includes('--check')) {
  if (!existsSync(outPath) || readFileSync(outPath, 'utf8') !== json) {
    console.error('test-vectors are stale. Run `pnpm --filter @mirthmix/game-engine vectors`.');
    process.exit(1);
  }
  console.log('Engine test vectors are up to date.');
} else {
  writeFileSync(outPath, json);
  console.log(`Wrote ${outPath}`);
}
